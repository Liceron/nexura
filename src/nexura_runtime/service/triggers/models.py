"""Data models for webhooks, schedules, receipts, and durable trigger jobs."""

from __future__ import annotations

import time
from typing import Any, Literal

from pydantic import BaseModel, Field

MissedRunPolicy = Literal["skip", "fire_once", "fire_all"]
TriggerType = Literal["webhook", "schedule"]
JobStatus = Literal["pending", "claimed", "running", "completed", "failed"]


class WebhookConfig(BaseModel):
    """Configuration binding a webhook endpoint to a pinned workflow release."""

    endpoint_id: str
    workspace_id: str
    workflow_id: str
    release_id: str
    secret: str
    replay_window_seconds: int = 300
    is_active: bool = True
    # Legacy v1 signatures (not covering event_id) are accepted only for endpoints that
    # predate v2. Endpoints registered through the REST API always set this to False.
    allow_legacy_signature: bool = True


class WebhookEvent(BaseModel):
    """Incoming signed webhook event payload."""

    event_id: str
    endpoint_id: str
    payload: dict[str, Any]
    timestamp: float
    signature: str


class WebhookReceipt(BaseModel):
    """Stored receipt tracking deduplication and job linkage for a webhook event."""

    event_id: str
    endpoint_id: str
    workspace_id: str
    job_id: str
    received_at: float = Field(default_factory=time.time)


class ScheduleConfig(BaseModel):
    """Timezone-aware recurring schedule definition pinned to a workflow release."""

    schedule_id: str
    workspace_id: str
    workflow_id: str
    release_id: str
    cron_expr: str | None = None
    interval_seconds: float | None = None
    timezone: str = "UTC"
    missed_run_policy: MissedRunPolicy = "fire_once"
    next_run_at: float = 0.0
    last_run_at: float | None = None
    is_active: bool = True
    payload: dict[str, Any] = Field(default_factory=dict)


class DurableTriggerJob(BaseModel):
    """Authoritative durable job generated by a webhook or scheduled trigger."""

    job_id: str
    workspace_id: str
    trigger_type: TriggerType
    trigger_source_id: str  # endpoint_id or schedule_id
    workflow_id: str
    release_id: str
    payload: dict[str, Any] = Field(default_factory=dict)
    status: JobStatus = "pending"
    claimed_by: str | None = None
    claimed_at: float | None = None
    created_at: float = Field(default_factory=time.time)
    completed_at: float | None = None
    error_message: str | None = None
    # The run this job owns. A6 S10: a job owns one run for its life; a worker that reclaims
    # the job after its lease expired continues this run (WorkflowEngine.recover).
    run_id: str | None = None
    lease_expires_at: float | None = None  # queue lease; None when not claimed
    attempts: int = 0  # number of claims (initial claim plus lease-expiry reclaims)
    # Runs this job replaced. Only filled when a run without an execution journal (a legacy
    # run, or one killed before its first journal write) could not be continued and a new run
    # was started instead; the old retry_mode="new_run" that also filled it was removed (S12).
    previous_run_ids: list[str] = Field(default_factory=list)
