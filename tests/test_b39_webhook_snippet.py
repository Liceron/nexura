"""B39: the signing snippets Studio shows after webhook registration are accepted by the server.

The snippets are generated by ``studio-web/src/features/triggers/webhookSnippet.ts`` (loaded with
Node's built-in type stripping), then actually run: the Python snippet via ``exec`` with
``urllib.request.urlopen`` routed to an in-process ``TestClient``, the curl snippet via ``sh``
with a ``curl`` shell function that records its arguments instead of using the network. Each
delivery goes to the real ``POST /api/v1/triggers/webhooks/{id}/deliver`` route.
"""

from __future__ import annotations

import io
import json
import os
import shutil
import subprocess
import urllib.request
from pathlib import Path
from typing import Any

import pytest
from fastapi.testclient import TestClient

from nexura_runtime.service.api.app import create_api_app
from nexura_runtime.service.triggers.signatures import compute_webhook_signature, serialize_payload

ROOT = Path(__file__).resolve().parents[1]
SNIPPET_TS = ROOT / "studio-web" / "src" / "features" / "triggers" / "webhookSnippet.ts"
ORIGIN = "http://testserver"
SPEC = {
    "name": "B39 webhook target",
    "entry_node": "a",
    "nodes": {"a": {"id": "a", "handler": "synthetic_order_lookup"}},
    "terminal_nodes": ["a"],
}

# Shared with studio-web/tests/unit/b39_webhook_setup.test.tsx.
VECTOR_PAYLOAD = {"msg": "hello from a webhook", "b": [1, 2, {"z": None, "a": True}], "hi": "नमस्ते"}
VECTOR_CANONICAL = (
    '{"b":[1,2,{"a":true,"z":null}],"hi":"\\u0928\\u092e\\u0938\\u094d\\u0924\\u0947",'
    '"msg":"hello from a webhook"}'
)
VECTOR_SIGNATURE = "a79d85f0bac76bcbc78e86a999b36a3607e5e290cb4e0d900a23f24d56233077"


def _node_supports_ts() -> bool:
    node = shutil.which("node")
    if not node:
        return False
    out = subprocess.run(
        [node, "--version"], capture_output=True, text=True, check=False, timeout=30
    ).stdout
    try:
        major, minor = (int(p) for p in out.strip().lstrip("v").split(".")[:2])
    except ValueError:
        return False
    return (major, minor) >= (22, 18)  # type stripping is on by default from here


needs_node = pytest.mark.skipif(
    not _node_supports_ts(), reason="needs Node >= 22.18 (type stripping)"
)


def _snippet_module(call: str) -> Any:
    """Evaluate ``call`` (an expression over module ``m``) in Node and return it as JSON."""
    script = (
        f"import * as m from {json.dumps(SNIPPET_TS.as_uri())};\n"
        f"process.stdout.write(JSON.stringify({call}));\n"
    )
    proc = subprocess.run(
        ["node", "--no-warnings", "--input-type=module", "-e", script],
        capture_output=True,
        text=True,
        check=True,
        timeout=60,
    )
    return json.loads(proc.stdout)


@pytest.fixture()
def service(tmp_path: Path) -> tuple[TestClient, str]:
    client = TestClient(create_api_app(db_path=tmp_path / "b39.db"))
    r = client.post("/api/v1/workflows", json={"workflow_id": "wf-b39", "spec": SPEC})
    assert r.status_code in (200, 201), r.text
    # Registered exactly as Studio does it: no secret supplied, the server generates one.
    reg = client.post(
        "/api/v1/triggers/webhooks", json={"endpoint_id": "orders", "workflow_id": "wf-b39"}
    )
    assert reg.status_code == 200, reg.text
    body = reg.json()
    assert body["signature_scheme"] == "v2"
    return client, body["secret"]


def _forward(client: TestClient, url: str, headers: dict[str, str], data: bytes) -> Any:
    assert url.startswith(ORIGIN), url
    return client.post(url[len(ORIGIN) :], content=data, headers=headers)


def _jobs(client: TestClient) -> list[dict[str, Any]]:
    return [
        j
        for j in client.get("/api/v1/triggers/jobs").json()["jobs"]
        if j["trigger_type"] == "webhook"
    ]


def test_reference_vector_matches_server_scheme() -> None:
    """The vector the vitest snippet test asserts is what the server computes."""
    assert serialize_payload(VECTOR_PAYLOAD).decode() == VECTOR_CANONICAL
    sig = compute_webhook_signature("test-secret-b39", 1700000000.9, VECTOR_PAYLOAD, "evt-b39-1")
    assert sig == VECTOR_SIGNATURE


@needs_node
def test_canonical_json_matches_python_json_dumps() -> None:
    corpus: list[Any] = [
        VECTOR_PAYLOAD,
        {"z": 1, "a": {"y": [3, {"k": "v"}], "b": None}, "m": False},
        {"quote": 'say "hi"', "slash": "a\\b/c", "ctl": "line\nnext\ttab\u0001", "emoji": "x😀y"},
        {"num": [0, -1, 123456789, 1.5, -2.25], "empty": {}, "list": []},
        {"Zebra": 1, "apple": 2, "_u": 3, "1": 4},
    ]
    got = _snippet_module(f"{json.dumps(corpus)}.map((v) => m.canonicalJson(v))")
    assert got == [serialize_payload(v).decode() for v in corpus]
    url = _snippet_module("m.webhookDeliveryUrl('http://testserver/', 'orders')")
    assert url == f"{ORIGIN}/api/v1/triggers/webhooks/orders/deliver"


@needs_node
def test_python_snippet_is_accepted_by_deliver_route(
    service: tuple[TestClient, str], monkeypatch: pytest.MonkeyPatch
) -> None:
    client, secret = service
    url = _snippet_module("m.webhookDeliveryUrl('http://testserver', 'orders')")
    snippet = _snippet_module(f"m.buildPythonSnippet({{ deliveryUrl: {json.dumps(url)} }})")
    assert secret not in snippet

    responses: list[Any] = []

    class _Resp(io.BytesIO):
        def __init__(self, r: Any) -> None:
            super().__init__(r.content)
            self.status = r.status_code

        def __enter__(self) -> _Resp:
            return self

        def __exit__(self, *exc: object) -> None:
            self.close()

    def fake_urlopen(req: urllib.request.Request) -> _Resp:
        assert req.get_method() == "POST"
        headers = {k: v for k, v in req.header_items()}
        assert isinstance(req.data, bytes)
        r = _forward(client, req.full_url, headers, req.data)
        responses.append(r)
        return _Resp(r)

    monkeypatch.setattr(urllib.request, "urlopen", fake_urlopen)
    monkeypatch.setenv("NEXURA_WEBHOOK_SECRET", secret)
    exec(compile(snippet, "<b39 python snippet>", "exec"), {"__name__": "__b39__"})
    assert len(responses) == 1
    assert responses[0].status_code == 200, responses[0].text
    assert responses[0].json()["accepted"] is True
    assert responses[0].json()["is_duplicate"] is False
    assert len(_jobs(client)) == 1

    # Negative: the same snippet with the wrong secret is rejected and starts nothing.
    monkeypatch.setenv("NEXURA_WEBHOOK_SECRET", "not-the-secret")
    exec(compile(snippet, "<b39 python snippet>", "exec"), {"__name__": "__b39__"})
    assert len(responses) == 2
    assert responses[-1].status_code == 401
    assert responses[-1].json()["detail"]["code"] == "INVALID_SIGNATURE"
    assert len(_jobs(client)) == 1


def _run_curl_snippet(snippet: str, secret: str, tmp_path: Path) -> dict[str, Any]:
    """Run the snippet under sh with ``curl`` replaced by a recorder; return the request."""
    record = tmp_path / "curl-args"
    fake = (
        "curl() {\n"
        f"  : > {record}\n"
        f'  for a in "$@"; do printf \'%s\\0\' "$a" >> {record}; done\n'
        "}\n"
    )
    env = {**os.environ, "NEXURA_WEBHOOK_SECRET": secret}
    subprocess.run(["sh", "-c", fake + snippet], env=env, check=True, timeout=60)
    args = record.read_bytes().split(b"\0")[:-1]
    argv = [a.decode() for a in args]
    headers: dict[str, str] = {}
    data: bytes | None = None
    url = ""
    i = 0
    while i < len(argv):
        a = argv[i]
        if a == "-H":
            name, _, value = argv[i + 1].partition(":")
            headers[name.strip()] = value.strip()
            i += 2
        elif a == "-d":
            data = argv[i + 1].encode()
            i += 2
        elif a == "-X":
            assert argv[i + 1] == "POST"
            i += 2
        elif a == "-s":
            i += 1
        else:
            url = a
            i += 1
    assert data is not None and url
    return {"url": url, "headers": headers, "data": data}


@needs_node
@pytest.mark.skipif(not shutil.which("openssl"), reason="curl snippet signs with openssl")
def test_curl_snippet_is_accepted_by_deliver_route(
    service: tuple[TestClient, str], tmp_path: Path
) -> None:
    client, secret = service
    url = _snippet_module("m.webhookDeliveryUrl('http://testserver', 'orders')")
    snippet = _snippet_module(
        f"m.buildCurlSnippet({{ deliveryUrl: {json.dumps(url)}, "
        "payload: { order_id: 'ord_1001', note: \"it's shipped\", n: 3 } })"
    )
    assert secret not in snippet
    req = _run_curl_snippet(snippet, secret, tmp_path)
    assert set(req["headers"]) >= {
        "X-Webhook-Signature",
        "X-Webhook-Timestamp",
        "X-Webhook-Event-ID",
    }
    r = _forward(client, req["url"], req["headers"], req["data"])
    assert r.status_code == 200, r.text
    assert r.json()["accepted"] is True
    job = _jobs(client)[0]
    assert job["trigger_source_id"] == "orders"

    # Same signed request replayed: accepted once, no second job.
    again = _forward(client, req["url"], req["headers"], req["data"])
    assert again.status_code == 200 and again.json()["is_duplicate"] is True
    # Tampered body under the same signature: rejected.
    tampered = req["data"].replace(b"ord_1001", b"ord_9999")
    bad = _forward(client, req["url"], {**req["headers"], "X-Webhook-Event-ID": "evt-x"}, tampered)
    assert bad.status_code == 401
    assert len(_jobs(client)) == 1
