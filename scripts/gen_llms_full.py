"""Generate ``llms-full.txt``: the documentation index and every page it links, in one file.

    uv run python scripts/gen_llms_full.py          # rewrite llms-full.txt
    uv run python scripts/gen_llms_full.py --check  # exit 1 if it is out of date

The pages come from ``docs/README.md`` in the order they are first linked there, starting
with the index itself. ``llms.txt`` (hand-written) links to the same pages one by one; this
file is for tools that want the whole text at once. Output is deterministic so the test
suite (``tests/docs/test_llms_txt.py``) can compare it.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
INDEX = DOCS / "README.md"
OUTPUT = ROOT / "llms-full.txt"
REPO_URL = "https://github.com/Liceron/nexura/blob/main"

# A relative Markdown link to a page in docs/, with an optional #anchor.
_LINK = re.compile(r"\]\((?!https?://|mailto:|#)([^)#\s]+\.md)(?:#[^)]*)?\)")


def pages() -> list[Path]:
    """``docs/README.md`` followed by each docs page it links, once, in link order."""
    found: list[Path] = [INDEX]
    for target in _LINK.findall(INDEX.read_text(encoding="utf-8")):
        path = (DOCS / target).resolve()
        if path.parent != DOCS.resolve() or not path.is_file() or path in found:
            continue
        found.append(path)
    return found


def render() -> str:
    """The full text of ``llms-full.txt``."""
    parts = [
        "# Nexura documentation, full text\n\n"
        "> Generated by scripts/gen_llms_full.py from docs/README.md and the pages it links."
        " Do not edit by hand. The short index is llms.txt.\n"
    ]
    for path in pages():
        rel = path.relative_to(ROOT).as_posix()
        body = path.read_text(encoding="utf-8").strip("\n")
        parts.append(f"\n---\n\nSource: {REPO_URL}/{rel}\n\n{body}\n")
    return "".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT.name} is out of date; run scripts/gen_llms_full.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUTPUT.name} ({len(pages())} pages, {text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
